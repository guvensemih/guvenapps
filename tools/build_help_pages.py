#!/usr/bin/env python3
"""Builds the Güven Phone Help Guide pages from the app's own texts.

The guide's topics, their order and their paragraphs come from the guven-phone repository at the given
commit; that repository is only read. Use the commit the Google Play production package was built from,
so the site never describes unreleased work.

Usage:
  python3 -I tools/build_help_pages.py <guven-phone-commit> [--phone-repo PATH]

Writes guven-phone/yardim/ (Turkish) and en/guven-phone/help/ (English): one page listing the topics and
one page per topic. Pages written by an earlier run for a topic that no longer exists are removed.
"""
