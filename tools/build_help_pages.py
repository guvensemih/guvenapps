def e(text):
    return html.escape(text, quote=False)


class Phone:
    def __init__(self, repo, commit):
        self.repo, self.commit = repo, commit

    def show(self, path):
        return subprocess.run(
            ["git", "-C", str(self.repo), "show", f"{self.commit}:{path}"],
            capture_output=True, text=True, check=True,
        ).stdout

    def version(self):
        return re.search(r'versionName = "([^"]+)"', self.show("app/build.gradle.kts")).group(1)

    def topics(self):
        """(id, title resource, items resource) in the order the app lists them."""
        kt = self.show(HELP_SCREEN)
        enum = kt[kt.index("enum class HelpTopic"):kt.index("companion object")]
        return re.findall(r'"(\w+)",\s*R\.string\.(\w+),\s*R\.array\.(\w+)', enum)

    def resources(self, values, file):
        root = ET.fromstring(self.show(f"feature/settings/src/main/res/{values}/{file}"))
        strings = {s.get("name"): "".join(s.itertext()) for s in root.findall("string")}
        arrays = {a.get("name"): ["".join(i.itertext()) for i in a.findall("item")] for a in root.findall("string-array")}
        return strings, arrays


def slug(topic_id):
    return topic_id.replace("_", "-")


def style_block():
    # The help pages share the Güven Phone page's look, so its own style block is reused as it is.
    page = (SITE / "guven-phone/index.html").read_text(encoding="utf-8")
    return page[page.index("  <style>"):page.index("</style>") + len("</style>")]


def page(lang, c, title, path, other_path, body, commit):
    tr_url, en_url = (f"{BASE_URL}/{path}", f"{BASE_URL}/{other_path}") if lang == "tr" else (
        f"{BASE_URL}/{other_path}", f"{BASE_URL}/{path}")
    menu = "\n".join(f'      <a href="{href}">{e(text)}</a>' for href, text in c["menu"])
    if lang == "tr":
        switch = f'      <span aria-current="page">Türkçe</span>\n      <a href="/{other_path}" lang="en">English</a>'
    else:
        switch = f'      <a href="/{other_path}" lang="tr">Türkçe</a>\n      <span aria-current="page">English</span>'
    main_id, skip_text = c["skip"]
    return f"""<!DOCTYPE html>
<!-- {MARKER} from guven-phone {commit}; do not edit by hand. -->
<html lang="{lang}">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>{e(title)}</title>
  <link rel="canonical" href="{BASE_URL}/{path}">
  <link rel="alternate" hreflang="tr" href="{tr_url}">
  <link rel="alternate" hreflang="en" href="{en_url}">
  <link rel="alternate" hreflang="x-default" href="{tr_url}">
{style_block()}
  <link rel="icon" href="/assets/guven-apps-icon.svg" type="image/svg+xml">
  <link rel="stylesheet" href="/assets/site.css">
</head>
<body>
  <a class="skip-link" href="#{main_id}">{e(skip_text)}</a>

  <header class="site-header">
    <p class="site-brand">
      <img src="/assets/guven-apps-icon.svg" alt="" width="40" height="40">
      Güven Apps
    </p>
    <nav class="site-nav" aria-label="{c["menu_label"]}">
{menu}
    </nav>
    <nav class="language-switcher" aria-label="{c["switch_label"]}">
{switch}
    </nav>
  </header>

  <main id="{main_id}">
{body}

    <section>
      <h2>{e(c["feedback_h2"])}</h2>
      <p>{c["feedback"]}</p>
    </section>
  </main>

  <footer>
    <p>{e(c["footer"])}</p>
  </footer>
</body>
</html>
"""


def build(phone, lang, topics, version):
    c = LANGS[lang]
    other = LANGS["en" if lang == "tr" else "tr"]
    strings, _ = phone.resources(c["values"], "strings_settings.xml")
    help_strings, help_arrays = phone.resources(c["values"], "strings_help.xml")
    guide_title = strings["settings_help_title"]
    guide = c["guide"].format(title=guide_title)
    out_dir = SITE / c["dir"]
    entries = [(slug(i), help_strings[t], help_arrays[a]) for i, t, a in topics]

    links = "\n".join(f'        <li><a href="{s}/">{e(t)}</a></li>' for s, t, _ in entries)
    index_body = f"""    <div class="page-intro">
      <h1>{e(guide)}</h1>
      <p>{e(strings["settings_help_subtitle"])}</p>
      <p>{e(c["index_lead"].format(title=guide_title, version=version))}</p>
    </div>

    <section>
      <h2>{e(c["topics_h2"])}</h2>
      <ul>
{links}
      </ul>
    </section>"""
    write(out_dir / "index.html", page(
        lang, c, c["index_title"].format(title=guide_title),
        f'{c["dir"]}/', f'{other["dir"]}/', index_body, phone.commit))

    for n, (s, title, paragraphs) in enumerate(entries):
        nav = []
        if n > 0:
            prev_slug, prev_title, _ = entries[n - 1]
            nav.append(f'      <p><a href="../{prev_slug}/">{e(c["previous"].format(topic=prev_title))}</a></p>')
        if n < len(entries) - 1:
            next_slug, next_title, _ = entries[n + 1]
            nav.append(f'      <p><a href="../{next_slug}/">{e(c["next"].format(topic=next_title))}</a></p>')
        nav.append(f'      <p><a href="../">{e(c["all_topics"].format(guide=guide))}</a></p>')
        text = "\n".join(f"      <p>{e(p)}</p>" for p in paragraphs)
        body = f"""    <div class="page-intro">
      <h1>{e(title)}</h1>
      <p><a href="../">{e(guide)}</a>, {e(c["topic_meta"].format(version=version))}</p>
    </div>

    <section>
{text}
    </section>

    <nav aria-label="{c["topic_nav_label"]}">
{chr(10).join(nav)}
    </nav>"""
        write(out_dir / s / "index.html", page(
            lang, c, c["topic_title"].format(topic=title, title=guide_title),
            f'{c["dir"]}/{s}/', f'{other["dir"]}/{s}/', body, phone.commit))

    current = {s for s, _, _ in entries}
    for old in out_dir.iterdir():
        index = old / "index.html"
        if old.is_dir() and old.name not in current and index.is_file() and MARKER in index.read_text(encoding="utf-8"):
            shutil.rmtree(old)
            print("removed", old.relative_to(SITE))
    print(f"{c['dir']}: {len(entries)} topics, {sum(len(p) for _, _, p in entries)} paragraphs, version {version}")


def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("commit", help="guven-phone commit the production package was built from")
    parser.add_argument("--phone-repo", type=Path, default=Path.home() / "Developer/guven-phone")
    args = parser.parse_args()
    phone = Phone(args.phone_repo, args.commit)
    topics = phone.topics()
    version = phone.version()
    for lang in LANGS:
        build(phone, lang, topics, version)


if __name__ == "__main__":
    main()
